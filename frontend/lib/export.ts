import type { Note } from "./types";

export function generateMarkdown(note: Note): string {
  const title = note.title || note.original_filename;
  const date = new Intl.DateTimeFormat(undefined, {
    dateStyle: "full",
    timeStyle: "short",
  }).format(new Date(note.created_at));

  const sections: string[] = [];

  sections.push(`# ${title}\n`);
  sections.push(
    `> **Recorded:** ${date} | **Language:** ${note.detected_language_name || note.source_language}${note.is_code_switched ? " (Code-switched)" : ""} | **File:** ${note.original_filename}\n`,
  );

  if (note.structured_data) {
    const { overview, key_points, action_items, decisions, topics } = note.structured_data;

    if (topics && topics.length > 0) {
      sections.push(`**Topics:** ${topics.map((t) => `\`${t}\``).join(" ")}\n`);
    }

    if (overview) {
      sections.push(`## Executive Overview\n\n${overview}\n`);
    }

    if (key_points && key_points.length > 0) {
      sections.push(`## Key Highlights\n`);
      for (const pt of key_points) {
        sections.push(`- ${pt}`);
      }
      sections.push("");
    }

    if (action_items && action_items.length > 0) {
      sections.push(`## Action Items\n`);
      for (const item of action_items) {
        const mark = item.completed ? "x" : " ";
        const owner = item.owner ? ` (@${item.owner})` : "";
        sections.push(`- [${mark}] **[${item.priority.toUpperCase()}]** ${item.task}${owner}`);
      }
      sections.push("");
    }

    if (decisions && decisions.length > 0) {
      sections.push(`## Key Decisions\n`);
      for (const dec of decisions) {
        const rationale = dec.rationale ? `\n  - *Rationale:* ${dec.rationale}` : "";
        sections.push(`- **${dec.decision}**${rationale}`);
      }
      sections.push("");
    }
  } else if (note.summary) {
    sections.push(`## Summary\n\n${note.summary}\n`);
  }

  if (note.transcript) {
    sections.push(`## Verbatim Transcript\n\n${note.transcript}\n`);
  }

  sections.push(`---\n*Generated by Audio Notes AI Studio*`);
  return sections.join("\n");
}

export function generatePlainText(note: Note): string {
  const title = note.title || note.original_filename;
  const sections: string[] = [title, "=".repeat(title.length), ""];

  if (note.structured_data) {
    const { overview, key_points, action_items, decisions, topics } = note.structured_data;
    if (topics && topics.length > 0) {
      sections.push(`TOPICS: ${topics.join(", ")}\n`);
    }
    if (overview) {
      sections.push(`OVERVIEW:\n${overview}\n`);
    }
    if (key_points && key_points.length > 0) {
      sections.push("KEY POINTS:");
      for (const pt of key_points) {
        sections.push(`• ${pt}`);
      }
      sections.push("");
    }
    if (action_items && action_items.length > 0) {
      sections.push("ACTION ITEMS:");
      for (const item of action_items) {
        const status = item.completed ? "[DONE]" : "[TODO]";
        const owner = item.owner ? ` (${item.owner})` : "";
        sections.push(`• ${status} [${item.priority.toUpperCase()}] ${item.task}${owner}`);
      }
      sections.push("");
    }
    if (decisions && decisions.length > 0) {
      sections.push("KEY DECISIONS:");
      for (const dec of decisions) {
        const rat = dec.rationale ? ` (Rationale: ${dec.rationale})` : "";
        sections.push(`• ${dec.decision}${rat}`);
      }
      sections.push("");
    }
  } else if (note.summary) {
    sections.push(`SUMMARY:\n${note.summary}\n`);
  }

  if (note.transcript) {
    sections.push(`TRANSCRIPT:\n${note.transcript}\n`);
  }

  return sections.join("\n");
}

export function downloadFile(content: string, filename: string, mimeType: string): void {
  if (typeof window === "undefined") return;
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
